def sync_docx(path: Path, items: list[tuple[str, str]]) -> str:
    doc = Document(path)
    existing = "\n".join(paragraph.text for paragraph in doc.paragraphs)
    marker = "\u9879\u76ee\u7ec4\u81ea\u67e5\u540c\u6b65\u8865\u5145"
    if marker in existing:
        return normalize_docx(doc, path, skipped=True)

    old_marker = "\u0043\u006f\u0064\u0065\u0078 \u81ea\u67e5\u540c\u6b65\u8865\u5145"
    if old_marker in existing:
        return normalize_docx(doc, path, skipped=True)

    doc.add_page_break()
    doc.add_heading(marker, level=1)
    for title, body in items:
        doc.add_heading(title, level=2)
        doc.add_paragraph(body)
    return normalize_docx(doc, path, skipped=False)


