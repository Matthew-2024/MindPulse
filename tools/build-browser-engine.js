import { readFile, writeFile } from "node:fs/promises";

const sourceFiles = [
  "src/rules/signals.js",
  "src/rules/recovery-score.js",
  "src/rules/risk-assessment.js",
  "src/rules/recommendation.js",
  "src/rules/policy-sdk.js",
  "src/rules/intervention-feedback.js",
  "src/rules/personalization.js"
];

function browserSource(source) {
  return source
    .replace(/^import\s+\{[\s\S]*?\}\s+from\s+["'][^"']+["'];?\s*/gm, "")
    .replace(/^export\s+(?=(?:function|const|let|var|class)\b)/gm, "")
    .replace(/^export\s*\{[^}]+\};?\s*$/gm, "")
    .trim();
}

const body = (await Promise.all(sourceFiles.map((file) => readFile(file, "utf8"))))
  .map(browserSource)
  .join("\n\n");

const output = [
  "// Generated by tools/build-browser-engine.js. Do not edit directly.",
  "(function (global) {",
  '  "use strict";',
  body.split("\n").map((line) => `  ${line}`).join("\n"),
  "",
  "  global.MindPulseRules = {",
  "    calculateRecoveryScore: calculateRecoveryScore,",
  "    assessRisk: assessRisk,",
  "    recommendPath: recommendPath,",
  "    evaluatePolicyCore: evaluatePolicyCore,",
  "    policyPackage: POLICY_PACKAGE,",
  "    policyPackageHash: POLICY_PACKAGE_HASH,",
  "    calculatePersonalBaseline: calculatePersonalBaseline,",
  "    personalizeRecommendation: personalizeRecommendation,",
  "    summarizeInterventionFeedback: summarizeInterventionFeedback,",
  "    feedbackEligibilityFor: feedbackEligibilityFor,",
  "    feedbackWindowFor: feedbackWindowFor,",
  "    dataCompletenessOf: dataCompletenessOf,",
  "    signalSnapshot: signalSnapshot,",
  "    signalPresent: signalPresent,",
  "    signalValueOf: signalValueOf,",
  "    signalSourceOf: signalSourceOf,",
  "    SIGNAL_KEYS: SIGNAL_KEYS,",
  "    SIGNAL_LABELS: SIGNAL_LABELS,",
  "    lowSleepDays: lowSleepDays,",
  "    recentNegativeCount: recentNegativeCount,",
  "    hasDangerSignal: hasDangerSignal,",
  "    dangerPatterns: DANGER_PATTERNS,",
  "    safePhrases: SAFE_PHRASES",
  "  };",
  "})(window);",
  ""
].join("\n");

await writeFile("src/rules/browser-engine.js", output, "utf8");
console.log(`Generated browser rules engine from ${sourceFiles.length} canonical module(s).`);
